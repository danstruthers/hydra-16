// commandmatch-gen.js - the test data for the 65C02 matcher (host side, in node).
// Writes cmd_table.h (the grammar's bytes, from commandtables.js), cmd_index.h (the index table's), cmd_alias.h (the
// default aliases') and cmd_corpus.h: each corpus line that is a plain command (not an answer, not an alias), with the
// words the world knows, and the reference result: whether the line parses (and the fewest adjuncts of any parse, now
// always 0). The matcher on the 65C02 must agree with these (sim/tools/commandmatch-test.js). And for the meaning
// (games/dq0c/cmdmean.s): cmd_words.h (the words' table, commandwords.js's) and cmd_lines.h (the lines it's tried on:
// every corpus line's, then cmdmatch/lines.txt's; commandmatch-test.js --mean has the host's meaning of each).
//   node sim/tools/commandmatch-gen.js <outdir>
'use strict';
const BS = String.fromCharCode(92);
const Q = String.fromCharCode(34);
const fs = require('fs');
const path = require('path');
const { loadRules, Compiler, buildContext, tokenize, DEFAULT_WORLD, matchRule, countRule, DEFAULT_ALIASES, segmentAliases } = require('./commandcompile.js');
const { encodeGrammar, encodeAliases, encodeIndex, indexWords, openNames } = require('./commandtables.js');
const words = require('./commandwords.js');

const GAME = path.join(__dirname, '..', '..', 'games', 'dq0');
const NOT_PLAIN = ['alias', 'unalias', 'forget'];

function cString(s) { return Q + s.split(BS).join(BS + BS).split(Q).join(BS + Q) + Q; }

function cArray(type, name, values, perLine) {
  const rows = [];
  for (let i = 0; i < values.length; i += perLine) rows.push('  ' + values.slice(i, i + perLine).join(', ') + ',');
  return `static const ${type} ${name}[${values.length}] = {\n${rows.join('\n')}\n};\n`;
}

// The lines the meaning is tried on: each corpus line's, then cmdmatch/lines.txt's
function meaningLines() {
  const read = file => fs.readFileSync(file, 'utf8').split('\n').map(l => l.replace(/\r$/, '')).filter(l => l.trim() && !l.startsWith('#'));
  return [...read(path.join(GAME, 'commands.corpus')).map(l => l.split('\t')[0]), ...read(path.join(__dirname, 'cmdmatch', 'lines.txt')).map(l => l.trim())];
}

function main() {
  const outDir = process.argv[2];
  if (!outDir) throw new Error('usage: commandmatch-gen.js <outdir>');
  const grammar = path.join(GAME, 'commands.ebnf');
  const rules = loadRules(grammar);
  const bytes = encodeGrammar(rules, openNames(grammar));
  const compiler = new Compiler(rules);

  const cases = [];
  const lines = fs.readFileSync(path.join(GAME, 'commands.corpus'), 'utf8').replace(/\r\n/g, '\n').split('\n');
  for (const raw of lines) {
    if (!raw.trim() || raw.startsWith('#')) continue;
    const [input, , , context] = raw.split('\t');
    const ctx = buildContext(context || '-', DEFAULT_WORLD);
    const toks = tokenize(input);
    const userAliases = [...ctx.aliases.keys()].some(k => !DEFAULT_ALIASES.has(k));
    if (ctx.pending || userAliases || !toks.length || (toks[0].k === 'w' && NOT_PLAIN.includes(toks[0].v))) continue;
    segmentAliases(toks, ctx);
    const env = compiler.envFor(toks, ctx);
    const parses = matchRule('line', 0, env).filter(r => r.end === toks.length);
    const adj = parses.length ? Math.min(...parses.map(p => countRule(p.kids[0], 'adjunct'))) : -1;
    cases.push({ input, ok: parses.length ? 1 : 0, adj,
      world: [...ctx.world].join(' '), names: [...ctx.names.keys()].join(' '), deities: [...ctx.deities].join(' ') });
  }

  fs.mkdirSync(outDir, { recursive: true });
  const abytes = encodeAliases();
  fs.writeFileSync(path.join(outDir, 'cmd_alias.h'), `/* generated by sim/tools/commandmatch-gen.js: the default aliases, ${abytes.length} bytes */
` +
    `#define CMD_ALIAS_LEN ${abytes.length}
` + cArray('unsigned char', 'cmd_alias', [...abytes].map(b => '0x' + b.toString(16).padStart(2, '0')), 16));
  const table = `/* generated by sim/tools/commandmatch-gen.js: the grammar table, ${bytes.length} bytes */\n` +
    `#define CMD_TABLE_LEN ${bytes.length}\n` + cArray('unsigned char', 'cmd_table', [...bytes].map(b => '0x' + b.toString(16).padStart(2, '0')), 16);
  fs.writeFileSync(path.join(outDir, 'cmd_table.h'), table);
  const ibytes = encodeIndex(rules, bytes);
  fs.writeFileSync(path.join(outDir, 'cmd_index.h'), `/* generated by sim/tools/commandmatch-gen.js: the index table, ${ibytes.length} bytes */
` +
    `#define CMD_INDEX_LEN ${ibytes.length}
` + cArray('unsigned char', 'cmd_index', [...ibytes].map(b => '0x' + b.toString(16).padStart(2, '0')), 16));
  const cs = cases;
  const corpus = `/* generated by sim/tools/commandmatch-gen.js: ${cs.length} corpus commands and their reference results */\n` +
    `#define CMD_CASES ${cs.length}\n` +
    cArray('char *const', 'cmd_text', cs.map(c => cString(c.input)), 1) +
    cArray('char *const', 'cmd_case_world', cs.map(c => cString(c.world)), 1) +
    cArray('char *const', 'cmd_case_names', cs.map(c => cString(c.names)), 1) +
    cArray('char *const', 'cmd_case_deities', cs.map(c => cString(c.deities)), 1) +
    cArray('signed char', 'cmd_ok', cs.map(c => c.ok), 24) +
    cArray('signed char', 'cmd_adj', cs.map(c => c.adj), 24);
  fs.writeFileSync(path.join(outDir, 'cmd_corpus.h'), corpus);
  const wbytes = words.encode(words.load(), indexWords(ibytes, bytes));
  fs.writeFileSync(path.join(outDir, 'cmd_words.h'), `/* generated by sim/tools/commandmatch-gen.js: the words' table, ${wbytes.length} bytes */
` + cArray('unsigned char', 'cmd_words', [...wbytes].map(b => '0x' + b.toString(16).padStart(2, '0')), 16));
  const ml = meaningLines();
  fs.writeFileSync(path.join(outDir, 'cmd_lines.h'), `/* generated by sim/tools/commandmatch-gen.js: ${ml.length} lines for the meaning */
#define CMD_LINES ${ml.length}
` + cArray('char *const', 'cmd_line', ml.map(cString), 1));
  console.log(`table ${bytes.length} bytes; ${cs.length} commands (of ${lines.filter(l => l.trim() && !l.startsWith('#')).length} corpus lines); ` +
    `${cs.filter(c => c.ok).length} parse`);
}

if (require.main === module) main();
module.exports = { meaningLines };
